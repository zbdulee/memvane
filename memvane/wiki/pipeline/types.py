PUBLISH_STATES = ('publishing', 'published', 'published_user_edited', 'conflict_user_edited', 'aborted')


class PipelineError(ValueError):
    """Raised when pipeline storage, path safety, or schema invariants fail."""


class StageQuotaExceeded(PipelineError):
    """Raised when charged staged bytes would exceed ``STAGE_QUOTA_BYTES``."""


@dataclass(frozen=True)
class PublishOutcome:
    tx_id: str
    target_path: str
    state: str
    live_sha: str | None = None
    displaced_sha: str | None = None


class PipelineHandle(Protocol):
    def close(self) -> None: ...
    def __enter__(self) -> PipelineHandle: ...
    def __exit__(self, exc_type: object, exc: object, tb: object) -> None: ...
    def meta_get(self, key: str) -> str | None: ...
    def meta_set(self, key: str, value: str) -> None: ...
    def record_refresh(self, event_id: str, source_path: str, ts: str, engine: str) -> dict: ...
    def unresolved_refreshes(self, source_path: str | None = None) -> list[dict]: ...
    def settle_refresh(self, event_id: str, sha256: str, reason: str, settled_at: float) -> bool: ...
    def resolve_refresh(self, event_id: str, resolved_at: float) -> bool: ...
    def resolve_refreshes_for_source(self, source_path: str, resolved_at: float, *, event_ids: list[str] | tuple[str, ...] | None = None) -> int: ...
    def enqueue_compile_job(self, job_id: str, source_collection: str, source_path: str, trigger: str, engine: str, payload: dict, *, replace_queued: bool = True) -> dict: ...
    def claim_compile_jobs(self, limit: int, claim_pid: int, claim_token: str) -> list[dict]: ...
    def complete_compile_job(self, job_id: str, claim_token: str, *, state: str = 'done') -> bool: ...
    def requeue_compile_jobs(self, job_ids: list[str] | tuple[str, ...], claim_token: str) -> int: ...
    def recover_dead_compile_claims(self, *, max_attempts: int = 3) -> dict: ...
    def count_compile_jobs(self, *, state: str | None = None) -> int: ...
    def enqueue_verify_job(self, job_id: str, target_path: str, source_hash: str | None, payload: dict) -> dict: ...
    def claim_verify_jobs(self, limit: int, claim_pid: int, claim_token: str, *, priority_targets: list[str] | tuple[str, ...] = (), reserve_backlog: bool = True) -> list[dict]: ...
    def complete_verify_job(self, job_id: str, claim_token: str, *, state: str = 'done') -> bool: ...
    def requeue_verify_jobs(self, job_ids: list[str] | tuple[str, ...], claim_token: str) -> int: ...
    def recover_dead_verify_claims(self, *, max_attempts: int = 3) -> dict: ...
    def count_verify_jobs(self, *, state: str | None = None) -> int: ...
    def insert_work(self, stage_id: str, queue: str, kind: str, phase: str, control_json: str, *, raw_blob: bytes | None, image_blob: bytes | None, charged_bytes: int = 0, target_path: str | None = None, quota_bytes: int | None = STAGE_QUOTA_BYTES) -> None: ...
    def get_work(self, stage_id: str) -> dict | None: ...
    def list_works(self, queue: str, kind: str, *, closed: bool = False) -> list[dict]: ...
    def works_for_target(self, target_path: str, *, closed: bool = False) -> list[dict]: ...
    def work_blob(self, stage_id: str, name: str) -> bytes | None: ...
    def cas_work(self, stage_id: str, expected_control_json: str, control_json: str, phase: str, *, closed: bool | None = None) -> bool: ...
    def delete_work(self, stage_id: str, expected_control_json: str) -> bool: ...
    def staged_quota_bytes(self) -> int: ...
    def append_generation(self, row: dict, *, origin_key: str | None = None) -> int | None: ...
    def generations(self, *, target_path: str | None = None, source_hash: str | None = None, canonical_key: str | None = None) -> list[dict]: ...
    def latest_generation(self, target_path: str) -> dict | None: ...
    def all_generations(self) -> list[dict]: ...
    def set_suppression(self, kind: str, key: str, body_hash: str, payload: dict) -> None: ...
    def get_suppression(self, kind: str, key: str) -> dict | None: ...
    def suppressions(self, kind: str) -> dict[str, str]: ...
    def enqueue_dedup_pair(self, page_a: str, page_b: str, score: float | None, payload: dict | None = None) -> bool: ...
    def dedup_pairs(self, *, state: str = 'queued') -> list[dict]: ...
    def set_dedup_pair_state(self, pair_key: str, state: str) -> bool: ...
    def append_audit(self, kind: str, payload: dict, *, target_path: str | None = None, source_path: str | None = None, body_hash: str | None = None) -> int: ...
    def query_audit(self, kind: str, *, target_path: str | None = None, source_path: str | None = None, body_hash: str | None = None, limit: int | None = None) -> list[dict]: ...
    def set_cooldown(self, scope: str, key: str, until_ts: float, meta: dict | None = None) -> None: ...
    def get_cooldown(self, scope: str, key: str) -> dict | None: ...
    def clear_cooldown(self, scope: str, key: str) -> bool: ...
    def set_fence(self, scope: str, reason: str, meta: dict | None = None) -> None: ...
    def get_fence(self, scope: str) -> dict | None: ...
    def clear_fence(self, scope: str) -> bool: ...
    def begin_publish_txn(self, target_path: str, temp_name: str, temp_ino: int, temp_sha: str, *, stage_id: str | None = None, expected_target_sha: str | None = None, tx_id: str | None = None, generation: dict | None = None) -> str: ...
    def finish_publish_txn(self, tx_id: str, state: str, *, audit_kind: str | None = None, audit_payload: dict | None = None) -> bool: ...
    def open_publish_txns(self, *, state: str = 'publishing') -> list[dict]: ...
