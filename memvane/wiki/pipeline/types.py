"""Domain constants, value objects, and Protocol handles for ``wiki/pipeline``."""
from __future__ import annotations

from dataclasses import dataclass
from typing import Protocol

DB_NAME = 'wiki-pipeline.sqlite3'
COMPILE_SUBDIR = '.memvane/compile'
PIPELINE_APP_ID = 0x4D565750
PIPELINE_USER_VERSION = 1
STAGE_QUOTA_BYTES = 64 * 1024 * 1024
HOOK_BUSY_TIMEOUT_MS = 150
WORKER_BUSY_TIMEOUT_MS = 5000
TEMP_PREFIX = '.publish-'
TEMP_SUFFIX = '.tmp'
FENCE_GLOBAL_PUBLISH = 'global_publish'

# Log-only kinds: no generation, deletion or resume decision reads them.
AUDIT_KINDS = (
    'candidate',
    'merge_needed',
    'discard',
    'verify_log',
    'verify_deleted',
    'dedup_deleted',
    'migration',
)
SUPPRESSION_KINDS = ('verify', 'dedup')
DEDUP_STATES = ('queued', 'claimed', 'done')
REFRESH_STATES = ('pending', 'settled', 'resolved')
