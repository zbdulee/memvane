"""The wiki/verify tests' project: one raw source, one generated card, one verify job.

``VerifyCase`` builds a ``.memvane`` project (minimal settings) with
``docs/source.md`` and a generated card at ``CARD_REL`` carrying an auto block,
and queues the job the compiler would write for it. ``run`` drains the queue
in process through ``verify.api.run`` with the expanded config; a host CLI is
``FakeEngines`` (``fake``). Without a selected route the legacy machine-delete
defaults (``onFail``/``onInconclusive: delete``) apply.
"""
from __future__ import annotations

import json
from pathlib import Path

from tests.support import settings_fake
from tests.support.case import FixtureCase
from tests.support.engines_fake import FakeEngines
from tests.support.project import make_project

CARD_REL = '.memvane/wiki/concepts/test-card.md'
HASH = 'abc123'
SOURCE_REL = 'docs/source.md'
SOURCE = '# Source\n\nDurable claim: the source documents cite markdown.\n'
CLAIM = {'claim': 'c', 'supported': True, 'quote': 'q', 'sourcePath': SOURCE_REL}
PASS = {'verdict': 'pass', 'claims': [CLAIM], 'reasons': []}
FAIL = {'verdict': 'fail', 'claims': [{**CLAIM, 'supported': False, 'quote': ''}],
        'reasons': ['source contradicts claim']}
INCONCLUSIVE = {'verdict': 'inconclusive', 'claims': [], 'reasons': ['verifier could not adjudicate']}
# The compiler's job field naming the source fingerprint spec (wiki_compile_worker).
SOURCE_FINGERPRINTS_SCHEMA = 'memvane-compile-source-fingerprints-v1'


def card_text(status='generated', source_hash=HASH, extra_fm=''):
    extra = extra_fm + '\n' if extra_fm else ''
    return (f'---\ntitle: "Test Card"\nstatus: {status}\ncreatedBy: memvane\n{extra}---\n\n'
            '> Auto-generated by MemVane from conversation/work context. Review, edit, or delete if wrong.\n\n'
            f'<!-- qmd:auto:start id="main" sourceHash="{source_hash}" -->\n'
            '## Summary\nDurable claim: the source documents cite markdown.\n<!-- qmd:auto:end -->\n')


def jsonl(path):
    path = Path(path)
    if not path.exists():
        return []
    return [json.loads(line) for line in path.read_text(encoding='utf-8').splitlines() if line.strip()]


class VerifyCase(FixtureCase):
    def setUp(self):
        super().setUp()
        self.project = make_project(self.home, git=False)
        self.root = self.project.root.resolve()
        self.compile_dir = self.root / '.memvane' / 'compile'
        self.compile_dir.mkdir(parents=True)
        self.queue = self.compile_dir / 'verify-queue.jsonl'
        self.card = self.root / CARD_REL
        self.source = self.root / SOURCE_REL

    # -- fixture -------------------------------------------------------------------
    def setup(self, *, card_status='generated', extra_fm='', with_source=True, **job):
        if with_source:
            self.project.write_note(SOURCE_REL, SOURCE)
        self.card.parent.mkdir(parents=True, exist_ok=True)
        self.card.write_text(card_text(card_status, extra_fm=extra_fm), encoding='utf-8')
        self.write_queue(self.job(with_source=with_source, **job))
        return self.card.read_text(encoding='utf-8')

    def job(self, *, with_source=True, **overrides):
        job = {'ts': '2026-07-04T00:00:00Z', 'targetPath': CARD_REL,
               'sources': [{'kind': 'file', 'path': SOURCE_REL, 'collection': self.project.raw_name}],
               'sourceHash': HASH, 'engine': 'claude', 'trigger': 'post_tool_source'}
        if with_source:
            job['sourceRevisions'] = [self.project.revision(self.source)]
        job.update(overrides)
        return job

    def write_queue(self, *jobs, raw=()):
        lines = [json.dumps(job) for job in jobs] + list(raw)
        self.queue.write_text(''.join(line + '\n' for line in lines), encoding='utf-8')

    def config(self, **compile_overrides):
        return settings_fake.expanded(self.project, compile=compile_overrides)

    def run_verify(self, produced=None, config=None, **compile_overrides):
        from memvane.wiki.verify import api as verify
        config = config or self.config(**compile_overrides)
        return verify.run(self.root, config, config['compile'], produced)

    def fake(self, verify=PASS, **kwargs):
        return FakeEngines({'verify': verify}, **kwargs).install(self)

    # -- observation -------------------------------------------------------------------
    def ledger(self, name):
        return jsonl(self.compile_dir / name)

    def log(self):
        return self.ledger('verify-log.jsonl')

    def queued(self):
        return self.queue.read_text(encoding='utf-8') if self.queue.exists() else ''

    def card_now(self):
        return self.card.read_text(encoding='utf-8')

    def frontmatter(self):
        text = self.card_now()
        return text[:text.index('\n---\n', 4)]

    def engine_cooldown(self):
        path = self.compile_dir / 'verify-engine-cooldown.json'
        return json.loads(path.read_text(encoding='utf-8')) if path.exists() else {}

    def assert_status(self, status):
        self.assertRegex(self.card_now(), '(?m)^status: %s$' % status)
