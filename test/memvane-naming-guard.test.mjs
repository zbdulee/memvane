test('no user-facing earlier product name outside documented compatibility shims', () => {
  const files = execFileSync('git', ['ls-files', '-z', '--cached', '--others',
                                     '--exclude-standard'], {encoding: 'utf8'})
    .split('\0').filter((name) => name && !EXCLUDED.test(name));
  const offenders = [];
  for (const file of files) {
    let text;
    try {
      text = readFileSync(file, 'utf8');
    } catch {
      continue;  // deleted in the working tree
    }
    if (text.includes('\0')) continue;  // binary
    text.split('\n').forEach((line, index) => {
      if (!FORBIDDEN.test(line)) return;
      if ((ALLOWED[file] || []).some((pattern) => pattern.test(line))) return;
      offenders.push(`${file}:${index + 1}: ${line.trim().slice(0, 160)}`);
    });
  }
  assert.deepEqual(offenders, []);
});

test('every allowlisted shim still exists (no stale allowance)', () => {
  for (const [file, patterns] of Object.entries(ALLOWED)) {
    const lines = readFileSync(file, 'utf8').split('\n');
    for (const pattern of patterns) {
      assert.ok(lines.some((line) => pattern.test(line) && FORBIDDEN.test(line)),
                `${file}: ${pattern}`);
    }
  }
});

test('manifests carry one identity: memvane in memvane-marketplace', () => {
  const read = (path) => JSON.parse(readFileSync(path, 'utf8'));
  const version = read('package.json').version;
  for (const path of ['package.json', 'plugin.json', '.claude-plugin/plugin.json',
                      '.codex-plugin/plugin.json']) {
    const manifest = read(path);
    assert.equal(manifest.name, 'memvane', path);
    assert.equal(manifest.version, version, path);
    if (manifest.repository) {
      assert.equal(manifest.repository, 'https://github.com/zbdulee/memvane', path);
    }
  }
  for (const path of ['.claude-plugin/marketplace.json', '.agents/plugins/marketplace.json']) {
    const market = read(path);
    assert.equal(market.name, 'memvane-marketplace', path);
    assert.deepEqual(market.plugins.map((row) => [row.name, row.version]),
                     [['memvane', version]], path);
  }
  assert.match(readFileSync('plugin.yaml', 'utf8'),
               new RegExp(`^name: memvane\\nversion: "${version.replace(/\./g, '\\.')}"$`, 'm'));
});
