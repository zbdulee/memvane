  assert.equal(sel.lex_terms_absent_in_cut, 2, '부재가 위치 컷 안에 있다');
  assert.equal(sel.lex_gate, 'absent_terms_no_identifier_evidence');
  assert.equal(sel.lex_gate_applied, true);
