// recall 주입 정밀도: lex 게이트 · 매칭 위치 인용 · 안내문 축약.
//
// 실측 문제: 무관한 프롬프트 4/4에 550~790자가 주입됐다("오늘 점심 뭐 먹을까" → 보안 검토
// 카드 727자). minScore는 유사도가 아니라 순위 컷(1/rank)이라 "무관하면 넣지 않기"가
// 원리적으로 불가능하고, 유일하게 무관/관련을 가르는 신호가 **lex 히트 수**였다
// (무관 0/0/0 vs 관련 8/8/7 — 무관 카드는 전부 vec만으로 뽑혔다).
//
// 이 파일은 세 동작을 고정한다:
//   A. lex 0건 → 링크+title만 (본문·`↳` 원문경로 없음)
//   B. 데몬 `line`이 auto 블록 안이면 그 지점부터 인용
//   C. 안내문 축약 (인젝션 방어 문장은 유지)
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, statSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { removeTemp } from './helpers/temp.mjs';

const PROMPT = 'config layout decision 내용을 알려줘';
const BODY_PREFIX = '  | ';

function runRecall(payload, env = {}) {
  return execFileSync('python3', ['core/recall.py'], {
    input: JSON.stringify(payload),
    encoding: 'utf8',
    env: { ...process.env, ...env },
  });
}

function contextOf(payload, env = {}) {
  const out = runRecall(payload, env).trim();
  if (!out) return null;
  return JSON.parse(out).hookSpecificOutput.additionalContext;
}

function bodyLines(ctx) {
  return ctx.split('\n').filter((l) => l.startsWith('  |')).map((l) => l.slice(BODY_PREFIX.length));
}

function sourceLines(ctx) {
  return ctx.split('\n').filter((l) => l.startsWith('  ↳'));
}

const VERIFIED_FM = [
  'title: "카드 정식 제목 — 설정 레이아웃 결정"',
  'status: verified',
  'createdBy: qmd-auto-context',
  'sourceRevisions:',
  '  - __TRUST_REVISION__',
  'reviewed: false',
  'sources:',
  '  - {kind: "file", path: "docs/guide.md"}',
].join('\n');

// 실측 727자 케이스의 카드 본문 크기(~311자)를 재현한다 — 게이트의 절감 효과를
// 장난감 카드가 아니라 실제 분포로 재기 위함이다.
const REALISTIC_BODY = [
  '설정은 .auto-context/settings.json 한 곳에서만 읽는다. 레거시 .auto-context.json 은',
  'update 경로에서만 검증 후 이동하고, query-time recall 은 read-only fallback 만 한다.',
  'collections 가 비면 recall 은 no_collections 로 빈 출력이며, cwd 폴더명을 컬렉션으로',
  '삼는 fallback 은 없다. 미설정·미동의·거절 프로젝트는 무동작이 정답이다.',
].join('\n');

// 카드를 줄 배열로 만들고 각 문단의 **1-based 줄 번호**를 함께 돌려준다.
// 데몬 `line`은 파일 줄 번호이므로 테스트가 그 값을 정확히 알아야 한다.
function card(fm, paragraphs) {
  const lines = [
    '---',
    ...fm.split('\n'),
    '---',
    '',
    '> Auto-generated by qmd-auto-context from conversation/work context. Review, edit, or delete if wrong.',
    '',
    '<!-- qmd:auto:start id="main" sourceHash="deadbeef" -->',
    '## Summary',
  ];
  const marks = {};
  for (const [name, text] of Object.entries(paragraphs)) {
    marks[name] = lines.length + 1;
    lines.push(text, '');
  }
  lines.push('<!-- qmd:auto:end -->', '');
  return { text: lines.join('\n'), marks };
}

function withTrustedRevision(dir, body) {
  if (!/^status: verified$/m.test(body) || !/^createdBy: qmd-auto-context$/m.test(body)) return body;
  const relative = 'docs/guide.md';
  const source = join(dir, relative);
  const bytes = readFileSync(source);
  const stat = statSync(source, { bigint: true });
  const hash = createHash('sha256').update(bytes).digest('hex');
  const revision = `{kind: "file", path: "${relative}", collection: "proj-docs", sha256: "${hash}", size: ${stat.size}, mtimeNs: ${stat.mtimeNs}}`;
  if (body.includes('__TRUST_REVISION__')) return body.replace('__TRUST_REVISION__', revision);
  return body.replace(
    'createdBy: qmd-auto-context\n',
    `createdBy: qmd-auto-context\nsourceRevisions:\n  - ${revision}\n`,
  );
}

function withProject({ settings = {}, cards = {} }, fn) {
  const dir = mkdtempSync(join(tmpdir(), 'qmd-precision-'));
  mkdirSync(join(dir, '.auto-context', 'wiki', 'decisions'), { recursive: true });
  mkdirSync(join(dir, 'docs'), { recursive: true });
  writeFileSync(join(dir, 'docs', 'guide.md'), '# 원문\n내용\n');
  writeFileSync(join(dir, '.auto-context', 'settings.json'), JSON.stringify({
    indexing: true,
    collections: ['proj-wiki', 'proj-docs'],
    collectionPaths: { 'proj-wiki': '.auto-context/wiki', 'proj-docs': 'docs' },
    collectionRoles: { 'proj-wiki': 'wiki', 'proj-docs': 'raw' },
    recallStrategy: 'wikiOnly',
    topN: 3,
    ...settings,
  }));
  for (const [name, body] of Object.entries(cards)) {
    writeFileSync(join(dir, '.auto-context', 'wiki', 'decisions', name), withTrustedRevision(dir, body));
  }
  const fixture = join(dir, 'fixture.json');
  const lexFixture = join(dir, 'lex.json');
  const write = (results) => writeFileSync(fixture, JSON.stringify({ results }));
  const writeLex = (results) => writeFileSync(lexFixture, JSON.stringify({ results }));
  try {
    return fn({ dir, fixture, lexFixture, write, writeLex });
  } finally {
    removeTemp(dir);
  }
}

function report(label, ctx) {
  if (process.env.QMD_PRECISION_REPORT) {
    console.log(`[report] ${label}: ${ctx === null ? 'null' : ctx.length} chars`);
  }
}

function logLines(logPath) {
  return readFileSync(logPath, 'utf8').trim().split('\n').map((l) => JSON.parse(l));
}

