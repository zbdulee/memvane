// ── 리셋 경로: 동작으로 확인한다 ──────────────────────────────────────────────
// `VERIFY_PROOF_FIELDS` 멤버십 단정만으로는 "그 튜플을 실제로 경유하는가"가 증명되지
// 않는다. 남으면 새 본문에 옛 지문이 붙어 그 카드가 **영구 불일치**로 비가시가 된다.
test('소스 변경으로 카드가 갱신되면 verifiedBodyHash 가 키째 사라진다 (compile merge)', () => {
  const out = py([
    'import sys, json, tempfile, shutil',
    'from pathlib import Path',
    'sys.path.insert(0, "core")',
    'import wiki_compile as wc, yaml_scalars as ys',
    'd = Path(tempfile.mkdtemp())',
    'card = d / "c.md"',
    'old = ("---\\ntitle: \\"t\\"\\nstatus: generated\\ncreatedBy: qmd-auto-context\\n"',
    '       "sources:\\n  - {kind: \\"file\\", path: \\"a.md\\"}\\n---\\n"',
    '       "<!-- qmd:auto:start id=\\"main\\" sourceHash=\\"aa\\" -->\\n옛 본문\\n"',
    '       "<!-- qmd:auto:end -->\\n\\n## 수동\\n보존 대상\\n")',
    'card.write_bytes(old.encode("utf-8"))',
    // 검수 통과 상태를 실제 writer 로 만든다(status: verified + 증명 4필드).
    'wc.stamp_verification(card, "verified", "codex", "cross-engine",',
    '                      ys.card_body_hash(card.read_text(encoding="utf-8")))',
    'stamped = card.read_text(encoding="utf-8")',
    'assert "verifiedBodyHash" in stamped',
    // 소스가 바뀐 뒤의 재생성 페이지(status 는 generated 로 돌아온다).
    'new = ("---\\ntitle: \\"t\\"\\nstatus: generated\\ncreatedBy: qmd-auto-context\\n"',
    '       "sources:\\n  - {kind: \\"file\\", path: \\"a.md\\"}\\n---\\n"',
    '       "<!-- qmd:auto:start id=\\"main\\" sourceHash=\\"bb\\" -->\\n새 본문\\n"',
    '       "<!-- qmd:auto:end -->\\n")',
    'ok = wc.rewrite_generated_card(card, stamped, new)',
    'after = card.read_text(encoding="utf-8")',
    'shutil.rmtree(d)',
    'print(json.dumps({"ok": ok, "hasHash": "verifiedBodyHash" in after,',
    '                  "hasProof": "verifiedBy" in after,',
    '                  "status": "status: generated" in after,',
    '                  "keptManual": "보존 대상" in after,',
    '                  "newBody": "새 본문" in after}, ensure_ascii=False))',
  ].join('\n'));
  const r = JSON.parse(out);
  assert.equal(r.ok, true, '갱신이 성공해야 함');
  assert.equal(r.hasHash, false, 'verifiedBodyHash 가 남으면 새 본문에 옛 지문이 붙는다');
  assert.equal(r.hasProof, false, '증명 필드 전체가 함께 제거된다');
  assert.equal(r.status, true, 'status 는 generated 로 리셋된다(재검증 대상)');
  assert.equal(r.keptManual, true, '블록 밖 수동 섹션은 보존된다');
  assert.equal(r.newBody, true, '새 본문이 반영된다');
});

