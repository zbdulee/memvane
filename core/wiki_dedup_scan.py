#!/usr/bin/env python3
"""Retroactive wiki dedup scan on the selected route's memvane-db, plus the page
hashing shared by the dedup resolver and the verify worker.

``body_hash`` is the one normalized body hash both sides of skip suppression
use; ``load_skip_suppressions`` reads the append-only skip ledger.

``run`` finds near-duplicate wiki cards that already sit on disk and queues
each pair to ``.auto-context/compile/dedup-needed.jsonl`` for the
wiki-dedup-resolver agent (``skills/wiki-dedup``). It runs in the wiki
lifecycle child (``wiki_lifecycle.main``), which the project's
``laya-compile`` wake starts after SessionStart or a source edit; it has no
wake kind of its own.

Similarity is the cosine between per-card centroids of the chunk vectors the
selected route already stored for its sealed head generation
(``gen_vector_rows`` and ``vector_chunks``). The scan loads no model, sends
nothing to a provider and makes no paid call; the resolver agent judges every
queued pair. Only cards whose bytes on disk still hash to the indexed hash are
compared, so a card edited after the last publish waits for the next one.

Bounds per run: at most ``MAX_CARDS`` indexed cards, at most
``MAX_PAGES_PER_SCAN`` changed cards compared against the rest,
``compile.semanticDedup.maxPairsPerScan`` queued pairs, one pair per compared
card, and a ``DEADLINE_SECONDS`` wall clock. A per-project snapshot records
which indexed hash of each card was compared, so the next run compares only
new or changed cards; a card left out by a bound stays pending.

Fail-open: ``main`` always exits 0 and writes nothing to stdout; failures go
to the dedup log.
"""
from __future__ import annotations

import argparse
from contextlib import closing
from datetime import datetime, timezone
import hashlib
import json
import math
import os
from pathlib import Path
import re
import sys
import time

sys.path.insert(0, str(Path(__file__).parent.resolve()))
import memvane_paths
import wiki_compile as wc

BANNER_RE = re.compile(r"^> Auto-generated by (?:MemVane|qmd-auto-context).*\n+", re.M)
AUTO_MARKER_LINE_RE = re.compile(r"^<!-- qmd:auto:(start|end).*-->\n?", re.M)
SUMMARY_HEADING_RE = re.compile(r"^## Summary\n+", re.M)

EXCLUDED_STATUSES = {"superseded", "discarded"}
META_PAGES = ("index.md", "log.md")
SNAPSHOT_VERSION = 1
# Changed cards compared per run. Each is compared against every indexed card.
MAX_PAGES_PER_SCAN = 50
# Upper bound on chunk rows read from the head generation in one run.
MAX_VECTOR_ROWS = 50_000
DEADLINE_SECONDS = 20.0


def extract_body_text(text: str) -> str:
    """Strip frontmatter and the managed auto-block banner/markers/heading,
    leaving just the page's meaningful prose.
    Every auto-generated page shares the same ~20 lines of boilerplate; hashing
    the full file would make two identical bodies look different."""
    body = wc.FRONTMATTER_RE.sub("", text, count=1)
    body = BANNER_RE.sub("", body)
    body = AUTO_MARKER_LINE_RE.sub("", body)
    body = SUMMARY_HEADING_RE.sub("", body)
    return body.strip()


def body_hash(text: str) -> str:
    """Stable content hash of a page's normalized body text.

    Normalization is extract_body_text() plus a FIXED whitespace rule
    (CRLF -> LF, per-line trailing-whitespace strip, outer strip), sha256
    over UTF-8 bytes -- insensitive to line-ending/trailing-space churn.
    Shared by the verify worker's skip-suppression check, this scan and
    wiki_dedup_resolve.py's skip recording: the sides MUST hash
    identically or suppression never matches. Never duplicate this.
    """
    body = extract_body_text(text.replace("\r\n", "\n"))
    normalized = "\n".join(line.rstrip() for line in body.split("\n")).strip()
    return hashlib.sha256(normalized.encode("utf-8")).hexdigest()


def pair_key(a: str, b: str) -> tuple[str, str]:
    return tuple(sorted((a, b)))


def load_skip_suppressions(skipped_path: Path | None) -> dict[tuple[str, str], tuple[str, str]]:
    """Map sorted (pageA, pageB) -> (pageAHash, pageBHash), keeping only the
    LAST record per pair -- the file is append-only, so later records simply
    overwrite earlier ones during this in-order pass. Malformed rows are
    ignored (fail-open); rows stored unsorted are normalized, not dropped."""
    suppressions: dict[tuple[str, str], tuple[str, str]] = {}
    if skipped_path is None:
        return suppressions
    for row in wc.read_jsonl(skipped_path):
        page_a = row.get("pageA")
        page_b = row.get("pageB")
        hash_a = row.get("pageAHash")
        hash_b = row.get("pageBHash")
        if not all(isinstance(v, str) and v for v in (page_a, page_b, hash_a, hash_b)):
            continue
        key = pair_key(page_a, page_b)
        suppressions[key] = (hash_a, hash_b) if key == (page_a, page_b) else (hash_b, hash_a)
    return suppressions


def log_path() -> Path:
    return Path(os.environ.get(
        "QMD_WIKI_DEDUP_LOG",
        str(memvane_paths.auto_context_state() / "logs" / "wiki-dedup.log")))


def log(message: str) -> None:
    try:
        path = log_path()
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("a", encoding="utf-8") as handle:
            handle.write(f"[{datetime.now(timezone.utc).isoformat()}] {message}\n")
    except OSError:
        pass


def snapshot_path(project_key: str) -> Path:
    import scan_state
    return scan_state.state_dir() / f"{project_key}-wiki-dedup.json"


class _Card:
    """One indexed wiki card: its current bytes on disk and its stored centroid."""

    def __init__(self, rel: str, indexed_hash: str, centroid: list[float]):
        self.rel = rel
        self.indexed_hash = indexed_hash
        self.centroid = centroid
        self.text: str | None = None


def _centroid(vectors: list[tuple[float, ...]]) -> list[float] | None:
    dimension = len(vectors[0])
    total = [0.0] * dimension
    for vector in vectors:
        for index, value in enumerate(vector):
            total[index] += value
    norm = math.sqrt(sum(value * value for value in total))
    if not math.isfinite(norm) or norm <= 0:
        return None
    return [value / norm for value in total]


def indexed_cards(decision: dict, deadline: float) -> tuple[str, dict[str, _Card]]:
    """``(generation, {wiki-relative path: card})`` from the sealed head.

    Reads one read-only snapshot of the route's database: eligible,
    non-excluded wiki members of the published, sealed head generation and
    their chunk vectors for the route's vector profile.
    """
    from context_learning.laya_learning import _open, _sealed_head, wiki_names
    from laya_index_a import IndexContractError, _NOT_EXCLUDED
    from laya_index_vector import _unpack
    import wiki_source_retire

    names = wiki_names(decision)
    if len(names) != 1:
        raise ValueError("selected_dedup_wiki_collection_invalid")
    prefix = names[0] + "/"
    scope = decision["scopeId"]
    profile_id = decision["vectorProfile"]["profileId"]
    with closing(_open(decision)) as db:
        generation = _sealed_head(db, scope)
        seal = db.execute("SELECT profile_id FROM gen_vector_seals WHERE gen=? AND scope=?",
                          (generation, scope)).fetchone()
        if seal != (profile_id,):
            raise ValueError("selected_dedup_vector_profile_changed")
        profile = db.execute("SELECT dimension FROM vector_profiles WHERE profile_id=?",
                             (profile_id,)).fetchone()
        if profile is None or type(profile[0]) is not int or profile[0] < 1:
            raise ValueError("selected_dedup_vector_profile_invalid")
        dimension = profile[0]
        rows = db.execute(
            "SELECT m.path,m.hash,v.embedding FROM gen_vector_rows r "
            "JOIN membership m ON m.gen=r.gen AND m.scope=r.scope AND m.path=r.path "
            "AND m.hash=r.hash "
            "JOIN vector_chunks v ON v.hash=r.hash AND v.title=r.title "
            "AND v.profile_id=r.profile_id AND v.seq=r.seq "
            "WHERE r.gen=? AND r.scope=? AND r.profile_id=? AND m.eligible=1 "
            "AND substr(m.path,1,?)=? AND " + _NOT_EXCLUDED +
            " ORDER BY m.path COLLATE BINARY,r.seq",
            (generation, scope, profile_id, len(prefix), prefix)).fetchmany(MAX_VECTOR_ROWS + 1)
    if len(rows) > MAX_VECTOR_ROWS:
        raise ValueError("selected_dedup_vector_capacity")
    grouped: dict[str, tuple[str, list[tuple[float, ...]]]] = {}
    for path, indexed_hash, blob in rows:
        if time.monotonic() >= deadline:
            raise TimeoutError("selected_dedup_deadline")
        rel = path[len(prefix):]
        entry = grouped.setdefault(rel, (indexed_hash, []))
        if entry[0] != indexed_hash:
            raise ValueError("selected_dedup_membership_conflict")
        try:
            entry[1].append(_unpack(blob, dimension))
        except IndexContractError as exc:
            raise ValueError("selected_dedup_vector_invalid") from exc
    if len(grouped) > wiki_source_retire.MAX_CARDS:
        raise ValueError("selected_dedup_card_capacity")
    cards = {}
    for rel, (indexed_hash, vectors) in grouped.items():
        centroid = _centroid(vectors)
        if centroid is not None:
            cards[rel] = _Card(rel, indexed_hash, centroid)
    return generation, cards


def _current_text(wiki_root: Path, card: _Card) -> str | None:
    """The card's text only while its bytes still hash to the indexed hash.

    The hash is the same raw-byte sha256 the source port compares
    (``laya_index_source_port``). A card in scope must be a regular file under
    ``wiki_root``, not a meta page and not ``superseded``/``discarded``.
    """
    parts = Path(card.rel).parts
    if (not card.rel.endswith(".md") or any(part.startswith(".") for part in parts)
            or card.rel in META_PAGES):
        return None
    path = wiki_root / card.rel
    try:
        if path.is_symlink() or not path.is_file():
            return None
        data = path.read_bytes()
    except OSError:
        return None
    if hashlib.sha256(data).hexdigest() != card.indexed_hash:
        return None
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        return None
    meta, ok = wc.parse_frontmatter(text)
    status = str(meta.get("status") or "").strip().lower() if ok else ""
    if status in EXCLUDED_STATUSES:
        return None
    return text


def _cosine(left: list[float], right: list[float]) -> float:
    return sum(a * b for a, b in zip(left, right))


def run(cwd: str) -> dict:
    """One bounded scan for the project at ``cwd``; returns a summary."""
    import compile_paths as cp
    import config as qmd_config
    import scan_state
    import wiki_selected_laya

    result = {"state": "skipped", "cards": 0, "compared": 0, "queued": 0,
              "suppressed": 0, "pending": 0}
    found = qmd_config.find_project_config(cwd)
    root = Path(found["projectRoot"]).resolve()
    config = found["config"]
    compile_cfg = config.get("compile") if isinstance(config.get("compile"), dict) else {}
    if not qmd_config.compile_active(compile_cfg):
        log("SKIP: compile.mode is off")
        return result
    semantic_cfg = (compile_cfg.get("semanticDedup")
                    if isinstance(compile_cfg.get("semanticDedup"), dict) else {})
    if not semantic_cfg.get("enabled", True):
        log("SKIP: compile.semanticDedup.enabled is false")
        return result
    try:
        bound = wiki_selected_laya.selected(root)
    except ValueError as exc:
        log(f"DEFER: selected route unavailable ({exc})")
        result["state"] = "deferred"
        return result
    if bound is None:
        log("SKIP: no selected memvane-db route")
        return result
    decision = bound[0]
    wiki_root = wc.safe_managed_dir(root, config.get("wikiPath", ".auto-context/wiki"))
    selected_wiki = next(item["sourceRoot"] for item in decision["collections"]
                         if item["role"] == "wiki")
    if wiki_root is None or str(wiki_root.resolve()) != selected_wiki:
        log("ABORT: wiki root differs from the selected route")
        return result
    compile_dir = cp.compile_dir(root, create=True)
    queue_path = cp.ledger(root, cp.DEDUP_NEEDED)
    skipped_path = cp.ledger(root, cp.DEDUP_SKIPPED)
    if compile_dir is None or queue_path is None:
        log("ABORT: unsafe_compile_path")
        return result

    deadline = time.monotonic() + DEADLINE_SECONDS
    try:
        generation, cards = indexed_cards(decision, deadline)
    except (OSError, ValueError, TimeoutError) as exc:
        log(f"DEFER: memvane-db read failed ({exc})")
        result["state"] = "deferred"
        return result
    except Exception as exc:  # sqlite3 busy/locked under a running sync writer
        log(f"DEFER: memvane-db read failed ({type(exc).__name__})")
        result["state"] = "deferred"
        return result
    wiki_selected_laya.recheck(bound)
    result["cards"] = len(cards)

    snap_path = snapshot_path(scan_state.project_key(str(root), found.get("configPath")))
    previous = scan_state.read_state(snap_path)
    previous_files = previous.get("files") if isinstance(previous.get("files"), dict) else {}
    current_files = {rel: value for rel, value in previous_files.items()
                     if rel in cards and value == cards[rel].indexed_hash}
    for card in cards.values():
        card.text = _current_text(wiki_root, card)
    live = [card for card in cards.values() if card.text is not None]
    to_scan = sorted((card for card in live if current_files.get(card.rel) != card.indexed_hash),
                     key=lambda card: card.rel)

    try:
        max_pairs = int(semantic_cfg.get("maxPairsPerScan", 10) or 10)
    except (TypeError, ValueError):
        max_pairs = 10
    max_pairs = max(1, min(max_pairs, 100))
    threshold = qmd_config.DEDUP_AUTO_MERGE_THRESHOLD
    suppressions = load_skip_suppressions(skipped_path)
    # A resolver run holds its rows in `dedup-needed.jsonl.claimed.*` until it
    # requeues the unresolved ones; those pairs are queued too.
    queued_keys = {pair_key(str(row.get("pageA", "")), str(row.get("pageB", "")))
                   for path in (queue_path, *sorted(queue_path.parent.glob(
                       queue_path.name + ".claimed.*")))
                   if not path.is_symlink()
                   for row in wc.read_jsonl(path)}
    lines = []
    for card in to_scan:
        if (len(lines) >= max_pairs or result["compared"] >= MAX_PAGES_PER_SCAN
                or time.monotonic() >= deadline):
            break
        best = None
        for other in live:
            if other is card:
                continue
            score = _cosine(card.centroid, other.centroid)
            if score < threshold:
                continue
            key = pair_key(card.rel, other.rel)
            if key in queued_keys:
                continue
            recorded = suppressions.get(key)
            if recorded is not None:
                texts = {card.rel: card.text, other.rel: other.text}
                if (body_hash(texts[key[0]]), body_hash(texts[key[1]])) == recorded:
                    result["suppressed"] += 1
                    continue
            if best is None or (score, other.rel) > (best[0], best[1].rel):
                best = (score, other)
        result["compared"] += 1
        current_files[card.rel] = card.indexed_hash
        if best is None:
            continue
        score, other = best
        queued_keys.add(pair_key(card.rel, other.rel))
        lines.append(json.dumps({"pageA": card.rel, "pageB": other.rel,
                                 "score": round(score, 6)}, ensure_ascii=False))
    result["pending"] = len(to_scan) - result["compared"]
    if lines:
        from wiki_compile_worker import requeue_lines
        requeue_lines(queue_path, lines)
    result["queued"] = len(lines)
    # Written only after the queue append: a crash before it re-compares the
    # same cards next run, and `queued_keys` keeps a pair from doubling.
    scan_state.write_state_atomic(snap_path, {
        "version": SNAPSHOT_VERSION, "projectRoot": str(root),
        "generation": generation, "files": current_files})
    result["state"] = "scanned"
    log(f"generation={generation} cards={len(cards)} live={len(live)} "
        f"compared={result['compared']} pending={result['pending']} "
        f"queued={result['queued']} suppressed={result['suppressed']}")
    return result


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--cwd", default=os.getcwd())
    args = parser.parse_args()
    if os.environ.get("QMD_SANDBOX"):
        return 0
    try:
        run(args.cwd)
    except Exception as exc:  # fail-open: never break the caller
        log(f"EXCEPTION: {exc!r}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
